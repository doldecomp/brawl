f32 FExp(f32 x) {
    s16 exponent = F32ToS16(x * (1.0f / NW4R_MATH_LN_2));
    f32 remainder = x - NW4R_MATH_LN_2 * S16ToF32(exponent);
    f32 position = (NW4R_MATH_LN_2 + remainder) * (16.0f / NW4R_MATH_LN_2);
    u16 index = F32ToU16(position);
    f32 fraction = position - U16ToF32(index);
    f32 value = expTable[index].unk00 + fraction * expTable[index].unk04;
    u32 bits = F32AsU32(value) + (static_cast<u32>(exponent) << 23);
    return U32AsF32(bits & 0x7FFFFFFF);
}

f32 FLog(f32 x) {
    s16 exponent = FGetExpPart(x);
    f32 mantissa = FGetMantPart(x);
    f32 exponentValue = S16ToF32(exponent);
    f32 position = 256.0f * (mantissa - 1.0f);
    u16 index = F32ToU16(position);
    f32 fraction = position - U16ToF32(index);
    f32 logarithm = logTable[index].unk00 + fraction * logTable[index].unk04;
    return logarithm + NW4R_MATH_LN_2 * exponentValue;
}

