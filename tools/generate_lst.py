#!/usr/bin/env python3

"""
Generates include/RSBE01.lst (the symbol list modders link
against) from the symbols.txt of the DOL and every REL.

Usage:
  python3 tools/generate_lst.py [-o PATH] [--check] [--root DIR]

--check writes nothing and exits 1 if the output would change
    cheap enough to run from a pre-commit hook
--root reads the inputs from DIR instead of the repo, e.g. a checkout of
    the git index so the pre-commit hook only sees staged changes

Hand-written entries that symbols.txt can't express (hardware registers)
live in tools/lst_extras.txt. REL module ids are taken from the order of the
modules in config.yml (1-based), which matches the ids in the .rel headers.
"""

import argparse
import re
import sys
from pathlib import Path
from typing import Dict, List, Tuple

# Path Definitions
ROOT = Path(__file__).resolve().parent.parent
LST = ROOT / "include" / "RSBE01.lst"

# Inputs, relative to ROOT (or --root)
CONFIG = Path("config") / "RSBE01_02"
EXTRAS = Path("tools") / "lst_extras.txt"
CONFIG_YML = CONFIG / "config.yml"

# REL section index as used by RSBE01.lst
LST_SECTIONS = {".text": 1, ".ctors": 2, ".dtors": 3, ".rodata": 4, ".data": 5, ".bss": 6}

# Regexes
SYM_LINE = re.compile(r"^(\S+) = (\.?\w+):0x([0-9A-Fa-f]+); // type:(\w+)(?: size:0x[0-9A-Fa-f]+)?(?: scope:(\w+))?")
AUTO_NAME = re.compile(r"^(fn|lbl|gap|jumptable|FUN|dtor)_\w+$")
REL_ID = re.compile(r"^- object: \S*?([^/\s]+)\.rel\s*$", re.M)

HEADER = [
    "// Generated by tools/generate_lst.py from the symbols.txt files. Do not edit;",
    "// rename symbols in config/RSBE01_02 (or tools/lst_extras.txt) and regenerate.",
]


def load_modules(root: Path) -> Dict[str, int]:
    names = REL_ID.findall((root / CONFIG_YML).read_text())
    return {name: i for i, name in enumerate(names, 1)}


def wanted(name: str, typ: str, scope: str) -> bool:
    return typ in ("function", "object", "label") and scope != "local" and not name.startswith("@") and not AUTO_NAME.match(name)


def read_symbols(path: Path) -> List[Tuple[str, int, str]]:
    out = []
    for line in path.read_text().splitlines():
        m = SYM_LINE.match(line)
        if m and wanted(m.group(1), m.group(4), m.group(5) or ""):
            out.append((m.group(2), int(m.group(3), 16), m.group(1)))
    return out


def generate(root: Path) -> str:
    config = root / CONFIG
    extras = root / EXTRAS
    lines = list(HEADER)
    if extras.exists():
        lines += ["", *extras.read_text().splitlines()]

    syms = sorted({(a, n) for _, a, n in read_symbols(config / "symbols.txt")})
    lines += ["", "// main"] + [f"{a:08X}:{n}" for a, n in syms]

    modules = load_modules(root)
    for path in sorted((config / "rels").glob("*/symbols.txt"), key=lambda p: modules.get(p.parent.name, 0)):
        module = path.parent.name
        if module not in modules:
            sys.exit(f"error: {module} is not listed under modules in {CONFIG_YML.name}")
        groups: Dict[str, set] = {}
        for sec, addr, name in read_symbols(path):
            if sec not in LST_SECTIONS:
                continue  # extab/extabindex etc. aren't addressable by section index
            groups.setdefault(sec, set()).add((addr, name))
        for sec in sorted(groups, key=LST_SECTIONS.__getitem__):
            lines += ["", f"// {module} {sec}"]
            lines += [f"{modules[module]},{LST_SECTIONS[sec]},{a:X}: {n}" for a, n in sorted(groups[sec])]
    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("-o", "--output", type=Path, default=LST)
    parser.add_argument("--check", action="store_true", help="exit 1 if the output file is out of date")
    parser.add_argument("--root", type=Path, default=ROOT, help="directory to read the inputs from")
    args = parser.parse_args()

    text = generate(args.root)
    current = args.output.read_text() if args.output.exists() else None
    if args.check:
        if current != text:
            sys.exit(f"{args.output} is out of date; run tools/generate_lst.py")
        return

    if current != text:
        args.output.write_text(text)
        print(f"updated {args.output}")


if __name__ == "__main__":
    main()
